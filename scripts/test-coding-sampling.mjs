import assert from 'node:assert/strict';
import { humanWindow, humanText, atOrBefore, roundRobin } from '../frontend/src/services/codingSampling.ts';
const human = i => ({ id: String(i), senderUid: 'participant', type: 'text', content: `Idea ${i}`, timestamp: i * 100 });
const humans = Array.from({ length: 15 }, (_, i) => human(i));
const mixed = humans.flatMap(m => [m, { ...m, id: `ai${m.id}`, senderUid: 'ai_mentor', timestamp: m.timestamp + 1 }]);
assert.deepEqual(humanWindow(mixed, '7').map(m => m.id), humans.slice(2, 13).map(m => m.id));
assert.equal(humanWindow(mixed, '0').length, 6);
assert.equal(humanWindow(mixed, '14').length, 6);
assert.deepEqual(humanWindow(mixed, 'missing'), []);
assert.equal(humanText({ ...human(1), senderUid: 'system' }), false);
assert.equal(humanText({ ...human(1), type: 'whiteboard_state' }), false);
assert.equal(humanText({ ...human(1), content: '   ' }), false);
assert.equal(atOrBefore(mixed, -1), -1);
assert.equal(mixed[atOrBefore(mixed, 701)].id, '7');
const item = (id, ...kinds) => ({ id, events: kinds.map(kind => ({ kind, ref: id })) });
const pool = [item('a', 'intervention', 'random'), item('b', 'semantic', 'random'), item('c', 'tool', 'random'), item('d', 'random')];
const queue = roundRobin(pool, () => 0.99).reverse();
assert.deepEqual(queue.map(x => x.id), ['a', 'b', 'c', 'd']);
assert.equal(new Set(roundRobin([...pool, item('e', 'tool', 'semantic')])).size, 5);
assert.equal(roundRobin([]).length, 0);
console.log('Sampling tests passed: human-only windows, boundaries, pre-event anchors, source rotation, deduplication.');
