import assert from 'node:assert/strict';
import { codingTarget, mediaWindow, hasCodingMedia } from '../functions/src/codingMedia.js';
import { snapshotBank } from '../functions/src/codingBankVersions.js';
const text = (id, timestamp, senderUid = 'human') => ({ id, timestamp, senderUid, senderName: senderUid, type: 'text', content: id });
const image = { ...text('image', 2), type: 'file', content: '', fileData: { type: 'image', url: 'https://example.org/a.png' } };
const board = { ...text('board', 4, 'ai_mentor'), type: 'ai_asset', assetType: 'moodboard', assetPayload: { images: [{ url: 'https://example.org/b.png' }] }, content: 'AI prose must not be shown' };
const privateBoard = { ...text('private', 5), type: 'whiteboard_state', metadata: { isPrivate: true }, fileData: { type: 'image', url: 'private-preview' } };
const messages = [text('before', 1), image, text('ai', 3, 'ai_mentor'), board, privateBoard, text('after', 6)];
assert.equal(codingTarget(image), true);
assert.equal(codingTarget(board), false);
assert.equal(codingTarget(privateBoard), false);
assert.equal(hasCodingMedia(privateBoard), false);
assert.deepEqual(mediaWindow(messages, 'image').map(m => m.id), ['before', 'image', 'board', 'after']);
assert.equal(codingTarget({ ...image, status: 'failed' }), false);
const source = { id: 'room_1234', name: 'Test', messages, logs: [], events: [], semantic: [], mediaPolicy: 'multimodal-v1' };
const first = snapshotBank({ rooms: [source] }, null, 'first');
assert.equal(first.counts.questions, 3);
const edited = structuredClone(source); edited.messages[3].assetPayload.images[0].url = 'https://example.org/changed.png';
assert.equal(snapshotBank({ rooms: [edited] }, first.bank, 'changed').counts.changed, 3);
const plain = { ...source, messages: [text('onlytext', 1)] }; delete plain.mediaPolicy;
const legacy = snapshotBank({ rooms: [plain] }, null, 'legacy');
assert.equal(snapshotBank({ rooms: [{ ...plain, mediaPolicy: 'multimodal-v1' }] }, legacy.bank, 'new').counts.reused, 1);
const many = Array.from({ length: 20 }, (_, i) => text(`m${i}`, i));
assert.equal(mediaWindow(many, 'm10').length, 11);
console.log('Media tests passed: human image targets, AI artifact evidence without prose targets, private/failed exclusion, ±5 bounds, media change isolation, unchanged text compatibility.');
